//! 챕터 1: 시작하기 — 변수, 기본 타입, 함수
//!
//! 실행: cargo run --bin ch01_hello

fn main() {
    // ── 1. 변수와 가변성 ─────────────────────────────────────────
    // Rust의 변수는 기본적으로 "불변(immutable)"입니다.
    let x = 5;
    // x = 6; // ← 주석을 풀면 컴파일 에러! "cannot assign twice to immutable variable"

    // 변경하려면 `mut`을 붙입니다.
    let mut y = 5;
    y = 6;
    println!("x = {x}, y = {y}");

    // ── 1-1. 상수(const)와 변수 가리기(Shadowing) ───────────────
    // const는 컴파일 타임 상수이며 반드시 타입 명시가 필요합니다. 대문자 스네이크 케이스 관례.
    const THREE_HOURS_IN_SECONDS: u32 = 60 * 60 * 3;
    println!("3시간(초): {THREE_HOURS_IN_SECONDS}");

    // Shadowing: `let`을 다시 써서 이전 변수를 가립니다.
    // mut과 달리 '타입 변경'이 가능하며, 불변성을 유지하면서 변환 작업을 할 때 유용합니다.
    let spaces = "   "; // 문자열 슬라이스
    let spaces = spaces.len(); // 이제 spaces는 usize 숫자 타입!
    println!("spaces 공백 개수: {spaces}");

    // ── 2. 타입 추론과 기본 타입 ─────────────────────────────────
    let 정수: i32 = -42; // 부호 있는 32비트 정수 (기본 정수 타입)
    let 부호없는: u64 = 42; // 부호 없는 64비트 정수
    let 실수: f64 = 3.14; // 기본 부동소수점 타입
    let 참: bool = true;
    let 문자: char = '러'; // Rust의 char는 유니코드 한 글자 (4바이트)

    // 타입을 생략하면 컴파일러가 추론합니다.
    let 추론 = 10_i32 * 2; // 접미사로 타입 지정 가능
    println!("{정수} {부호없는} {실수} {참} {문자} {추론}");

    // ── 3. 기본 연산과 오버플로우 ────────────────────────────────
    println!("나눗셈(정수): 7 / 2 = {}", 7 / 2); // 소수점 버림
    println!("나머지: 7 % 2 = {}", 7 % 2);
    println!("나눗셈(실수): 7.0 / 2.0 = {}", 7.0_f32 / 2.0);

    // ── 4. 튜플과 배열 ───────────────────────────────────────────
    // 튜플: 타입이 서로 달라도 되는 고정 크기 묶음
    let person: (&str, i32) = ("김러스트", 30);
    // .0, .1 로 접근하거나 구조 분해로 꺼냅니다.
    let (name, age) = person;
    println!("이름: {name}, 나이: {age}");
    print!("튜플 첫 원소: {}, 두 번째 원소: {}\n", person.0, person.1);
    // 배열: 같은 타입의 고정 크기 묶음. 크기가 타입의 일부입니다.
    let numbers: [i32; 3] = [1, 2, 3];
    println!("배열 첫 원소: {}, 크기: {}", numbers[0], numbers.len());

    // ── 5. 함수와 반환값 ─────────────────────────────────────────
    // 마지막 "식(expression)"이 반환값이 됩니다. 세미콜론 없이!
    let sum = add(3, 4);
    println!("3 + 4 = {sum}");

    let double = |n: i32| n * 2; // 클로저(람다)도 이렇게 씁니다. 7장에서 자세히!
    println!("10의 두 배: {}", double(10));

    // ── 6. 형 변환 ───────────────────────────────────────────────
    // Rust는 자동 형변환을 하지 않습니다. `as` 또는 From/TryFrom(5장)을 사용합니다.
    let n: i32 = 300;
    let as_u8 = n as u8; // 잘려서 44가 됩니다 (300 - 256) — 주의!
    println!("300 as u8 = {as_u8} (오버플로우 주의)");

    // ── 연습 과제 ────────────────────────────────────────────────
    // 1) 화씨온도를 섭씨로 바꾸는 함수 f_to_c(f: f64) -> f64를 만들어 보세요.
    // 2) (이름, 나이) 튜플 3개를 만들고, 가장 나이가 많은 사람의 이름을 출력해 보세요.
    // 3) `let x = 5; x = 6;` 의 주석을 풀고 컴파일 에러 메시지를 읽어 보세요.
}

fn add(a: i32, b: i32) -> i32 {
    a + b // 세미콜론이 없으면 이 식이 반환값입니다. 세미콜론을 붙이면 컴파일 에러!
}
